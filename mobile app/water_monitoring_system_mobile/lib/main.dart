/// Initializes FCM, gets the device token, and sends it to the server.
Future<void> setupPushNotifications() async {
  final fcm = FirebaseMessaging.instance;

  // 1. Request notification permissions from the user (required for iOS).
  await fcm.requestPermission();

  // 2. Get the unique device token.
  final token = await fcm.getToken();
  print("📱 FCM Device Token: $token");

  // 3. Send the token to your Python backend.
  if (token != null) {
    await sendTokenToServer(token);
  }

  // 4. Listen for token updates and send them to the server as well.
  fcm.onTokenRefresh.listen((newToken) async {
    print("🔄 FCM Token Refreshed: $newToken");
    await sendTokenToServer(newToken);
  });
}

/// Sends the FCM token to your backend API.
Future<void> sendTokenToServer(String token) async {
  try {
    final response = await http.post(
      apiUri('register-device'),
      headers: {'Content-Type': 'application/json'},
      body: json.encode({'token': token}),
    );
    if (response.statusCode == 200) {
      print("✅ Token sent to server successfully.");
    } else {
      print(
          "⚠️ Failed to send token. Status: ${response.statusCode}, Body: ${response.body}");
    }
  } catch (e) {
    print("🔴 Error sending token to server: $e");
  }
}
